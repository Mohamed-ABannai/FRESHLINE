String normalizeBahrainLocation(String? value) {
  final String trimmed = (value ?? '').trim();
  if (trimmed.isEmpty) {
    return defaultBahrainLocation;
  }

  for (final String location in bahrainLocations) {
    if (location.toLowerCase() == trimmed.toLowerCase()) {
      return location;
    }
  }

  return defaultBahrainLocation;
}
